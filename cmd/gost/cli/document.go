package cli

import (
	"bytes"
	"fmt"
	"strings"

	M "github.com/metacubex/mihomo/common/yaml"
)

// Section is a top level section of the generated configuration.
type Section struct {
	Key    string
	Scalar any
	List   []Map
}

// Document is an ordered YAML document built for the generated configuration.
// Sections are kept in insertion order; mapping values are sorted by the YAML
// marshaler, which keeps the output deterministic.
type Document struct {
	sections []Section
}

// Map is a string keyed YAML mapping. Values keep their types so nested
// fragments are marshalled back unchanged.
type Map map[string]any

// MaskedValue is the text shown in place of secrets by --dry-run.
const MaskedValue = "***"

// NewDocument creates an empty document.
func NewDocument() *Document {
	return &Document{}
}

// Sections returns the sections of the document in order.
func (d *Document) Sections() []Section {
	return d.sections
}

// SetMap sets a scalar (usually mapping) top level section.
func (d *Document) SetMap(key string, value any) {
	for i := range d.sections {
		if d.sections[i].Key == key {
			d.sections[i] = Section{Key: key, Scalar: value}
			return
		}
	}
	d.sections = append(d.sections, Section{Key: key, Scalar: value})
}

// Append appends a mapping to a top level sequence section.
func (d *Document) Append(key string, value Map) {
	for i := range d.sections {
		if d.sections[i].Key != key {
			continue
		}
		d.sections[i].List = append(d.sections[i].List, value)
		return
	}
	d.sections = append(d.sections, Section{Key: key, List: []Map{value}})
}

// Marshal renders the document as YAML.
func (d *Document) Marshal() ([]byte, error) {
	return d.marshal(false)
}

// MaskedYAML renders the document with secrets masked, for --dry-run.
func (d *Document) MaskedYAML() (string, error) {
	buf, err := d.marshal(true)
	if err != nil {
		return "", err
	}
	return "# generated by mhm gost --dry-run (secrets masked)\n" + string(buf), nil
}

// MarshalYAML renders the document without masking, used by tests.
func (d *Document) MarshalYAML() (string, error) {
	buf, err := d.marshal(false)
	if err != nil {
		return "", err
	}
	return string(buf), nil
}

// InboundUDP reports whether the first listener enables UDP.
func (d *Document) InboundUDP() bool {
	for _, s := range d.sections {
		if s.Key != "listeners" || len(s.List) == 0 {
			continue
		}
		udp, ok := s.List[0]["udp"].(bool)
		return ok && udp
	}
	return false
}

// marshal writes the sections one by one; marshalling them individually keeps
// the top level order stable (a single mapping would be sorted by key).
func (d *Document) marshal(mask bool) ([]byte, error) {
	var out bytes.Buffer
	for _, s := range d.sections {
		fmt.Fprintf(&out, "%s:", s.Key)
		switch {
		case s.List != nil:
			out.WriteByte('\n')
			for _, item := range s.List {
				if mask {
					item = MaskMap("", item)
				}
				body, err := marshalValue(item)
				if err != nil {
					return nil, err
				}
				out.WriteString(indent(body, "  "))
			}
		default:
			body, err := marshalValue(s.Scalar)
			if err != nil {
				return nil, err
			}
			if isScalar(body) {
				out.WriteByte(' ')
				out.Write(body)
				continue
			}
			out.WriteByte('\n')
			out.WriteString(indent(body, "  "))
		}
	}
	return out.Bytes(), nil
}

// marshalValue renders a Go value as YAML.
func marshalValue(value any) (string, error) {
	buf, err := M.Marshal(value)
	if err != nil {
		return "", err
	}
	return string(buf), nil
}

// isScalar reports whether the rendered value is a single line.
func isScalar(body string) bool {
	return !bytes.Contains([]byte(trimTrailingNewline(body)), []byte("\n"))
}

func trimTrailingNewline(body string) string {
	for len(body) > 0 && (body[len(body)-1] == '\n' || body[len(body)-1] == '\r') {
		body = body[:len(body)-1]
	}
	return body
}

// indent prefixes every non empty line with the given prefix.
func indent(body, prefix string) string {
	body = trimTrailingNewline(body)
	var out bytes.Buffer
	for i, line := range bytes.Split([]byte(body), []byte("\n")) {
		if i > 0 {
			out.WriteByte('\n')
		}
		if len(line) == 0 {
			continue
		}
		out.WriteString(prefix)
		out.Write(line)
	}
	out.WriteByte('\n')
	return out.String()
}

// Clone returns a copy with one level of nested maps copied, so callers can
// add top level keys without touching the original fragment.
func (m Map) Clone() Map {
	out := make(Map, len(m)+2)
	for k, v := range m {
		if sub, ok := v.(Map); ok {
			copied := make(Map, len(sub))
			for sk, sv := range sub {
				copied[sk] = sv
			}
			out[k] = copied
			continue
		}
		out[k] = v
	}
	return out
}

// Inbound is a parsed -L argument.
type Inbound struct {
	// Type is the mihomo listener type, for example socks, http, mixed.
	Type string
	// Fields is the fragment to place in the listeners section.
	Fields Map
}

// Outbound is a parsed -F argument.
type Outbound struct {
	// Type is the mihomo outbound type, for example ss, socks5, trojan.
	Type   string
	Name   string
	Fields Map
}

// maskedSuffixes are key names whose values are masked in --dry-run output.
// uuid is treated as a secret as well: it is the credential of the matching
// protocols just like a password.
var maskedSuffixes = []string{
	"password", "psk", "token", "private-key", "auth", "auth-str",
	"obfs-password", "key", "pre-shared-key", "secret", "passphrase",
	"certificate", "client-auth-cert", "uuid",
}

// maskedPaths are nested keys that do not end in a masked suffix but still carry
// a secret.
var maskedPaths = []string{
	"reality-opts.public-key", "reality-opts.short-id", "users.password",
	"amnezia-wg-option.private-key", "shadow-tls-opts.password",
}

// ShouldMask reports whether the key at the given dotted path holds a secret.
func ShouldMask(path string) bool {
	lower := strings.ToLower(path)
	for _, suffix := range maskedSuffixes {
		if lower == suffix || strings.HasSuffix(lower, "."+suffix) {
			return true
		}
	}
	for _, masked := range maskedPaths {
		if strings.HasSuffix(lower, masked) {
			return true
		}
	}
	return false
}

// MaskMap replaces secret values with MaskedValue, recursively.
func MaskMap(prefix string, m Map) Map {
	out := make(Map, len(m))
	for k, v := range m {
		path := k
		if prefix != "" {
			path = prefix + "." + k
		}
		switch value := v.(type) {
		case Map:
			out[k] = MaskMap(path, value)
			continue
		case []Map:
			list := make([]Map, 0, len(value))
			for _, item := range value {
				list = append(list, MaskMap(path, item))
			}
			out[k] = list
			continue
		case []any:
			out[k] = maskList(path, value)
			continue
		}
		if ShouldMask(path) {
			out[k] = MaskedValue
			continue
		}
		out[k] = v
	}
	return out
}

// maskList masks list elements that are mappings: YAML fragments decode lists of
// mappings as []any, so the entries of a users list must be masked inside as
// well.
func maskList(path string, list []any) []any {
	out := make([]any, len(list))
	for i, item := range list {
		switch value := item.(type) {
		case map[string]any:
			out[i] = MaskMap(path, Map(value))
		case Map:
			out[i] = MaskMap(path, value)
		default:
			out[i] = item
		}
	}
	return out
}
